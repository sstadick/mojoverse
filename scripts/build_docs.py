"""Build the documentation hub and package sites, running every package's examples."""

from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

import yaml


PACKAGES = (
    "mojo-bio", "mojo-bstr", "mojo-io", "mojo-lapper", "mojo-libdeflate",
    "mojo-seqair", "mojo-threads",
)


def main():
    root = Path(__file__).resolve().parents[1]
    output = root / "target/docs"
    if output.exists() and not (output / ".mojoverse-generated").is_file():
        raise ValueError(f"Refusing to replace non-generated directory: {output}")
    with tempfile.TemporaryDirectory(prefix="mojoverse-site-") as directory:
        work = Path(directory)
        source = work / "source"
        source.mkdir()
        shutil.copyfile(root / "docs/index.md", source / "index.md")
        for name in PACKAGES:
            project = root / "packages" / name
            subprocess.run(
                ["pixi", "run", "--locked", "--manifest-path", str(project / "pixi.toml"), "docs"],
                cwd=root, check=True,
            )
            site = project / "target/docs"
            if not (site / ".mojoverse-generated").is_file() or not (site / "index.html").is_file():
                raise ValueError(f"Package documentation was not generated: {name}")
            shutil.copytree(site, source / name)
        config = {
            "site_name": "Mojoverse",
            "docs_dir": str(source),
            "site_dir": str(work / "site"),
            "use_directory_urls": False,
            "theme": {"name": "mkdocs"},
            "nav": [{"Libraries": "index.md"}],
            "repo_url": "https://github.com/sstadick/mojoverse",
            "edit_uri": "edit/main/docs/",
        }
        (work / "mkdocs.yml").write_text(yaml.safe_dump(config))
        subprocess.run([sys.executable, "-m", "mkdocs", "build", "--strict"], cwd=work, check=True)
        (work / "site/.mojoverse-generated").write_text("Generated by pixi run docs-site.\n")
        output.parent.mkdir(parents=True, exist_ok=True)
        if output.exists():
            shutil.rmtree(output)
        # Standalone 404 pages have root-relative links, not hub-relative ones.
        # Let the host serve its error page for the combined site instead.
        shutil.copytree(work / "site", output, ignore=shutil.ignore_patterns("404.html"))
    print(f"Built documentation hub and {len(PACKAGES)} package sites: {output}")


if __name__ == "__main__":
    main()
