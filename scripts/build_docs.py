"""Build the documentation hub and package sites, running every package's examples."""

import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile

from mojoverse.site import build_site, navigation
from mojoverse.versions import VERSIONS


PACKAGES = (
    "mojo-bio", "mojo-bstr", "mojo-io", "mojo-lapper", "mojo-libdeflate",
    "mojo-radix-sort", "mojo-threads",
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Checkout whose package sources, manifests and locks are documented")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--version", choices=[item["version"] for item in VERSIONS])
    args = parser.parse_args()
    root = args.source_root.resolve()
    output = args.output.resolve() if args.output else root / "target/docs"
    if output.exists() and not (output / ".mojoverse-generated").is_file():
        raise ValueError(f"Refusing to replace non-generated directory: {output}")
    with tempfile.TemporaryDirectory(prefix="mojoverse-site-") as directory:
        work = Path(directory)
        source = work / "source"
        source.mkdir()
        shutil.copyfile(root / "docs/index.md", source / "index.md")
        for name in PACKAGES:
            project = root / "packages" / name
            subprocess.run(
                ["pixi", "run", "--locked", "--manifest-path", str(project / "pixi.toml"), "docs"],
                cwd=root, check=True,
            )
            site = project / "target/docs"
            if not (site / ".mojoverse-generated").is_file() or not (site / "index.html").is_file():
                raise ValueError(f"Package documentation was not generated: {name}")
            shutil.copytree(site / "markdown", source / name)
            for api in site.glob("*.json"):
                shutil.copyfile(api, source / name / api.name)
        nav = [{"Libraries": "index.md"}]
        nav.extend({name: navigation(source / name, source)} for name in PACKAGES)
        # Installation and repository links must follow the documented checkout,
        # including when newer presentation tools build a stable release's docs.
        revision = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                                  capture_output=True, text=True)
        if revision.returncode == 0:
            commit = revision.stdout.strip()
            repository = "https://github.com/sstadick/mojoverse"
            for page in source.rglob("*.md"):
                text = page.read_text().replace(repository + "#", repository + f"/tree/{commit}#")
                text = text.replace(repository + "/tree/main/", repository + f"/tree/{commit}/")
                text = text.replace(repository + "/blob/main/", repository + f"/blob/{commit}/")
                page.write_text(text)
        build_site(source, work / "site", "Mojoverse", nav, catalog=True, version=args.version)
        (work / "site/.mojoverse-generated").write_text("Generated by pixi run docs-site.\n")
        output.parent.mkdir(parents=True, exist_ok=True)
        if output.exists():
            shutil.rmtree(output)
        shutil.copytree(work / "site", output)
    print(f"Built documentation hub and {len(PACKAGES)} package sites: {output}")


if __name__ == "__main__":
    main()
