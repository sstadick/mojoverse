"""Assemble independently built documentation versions for GitHub Pages."""

from html import escape
import json
import os
from pathlib import Path
import shutil
import tempfile
from urllib.parse import quote


SITE_URL = "https://sstadick.github.io/mojoverse/"
VERSIONS = [
    {"version": "nightly", "title": "Nightly (main)", "aliases": []},
    {"version": "stable-1.2", "title": "Stable (Mojo 1.2)", "aliases": []},
]
MARKER = ".mojoverse-generated"


def assemble_sites(nightly, stable, output):
    """Publish both versions together; retain old page URLs as nightly redirects."""
    sources = {"nightly": Path(nightly).resolve(), "stable-1.2": Path(stable).resolve()}
    output = Path(output).resolve()
    for name, source in sources.items():
        if not (source / MARKER).is_file() or not (source / "index.html").is_file():
            raise ValueError(f"Missing generated documentation for {name}: {source}")
        if source.is_relative_to(output) or output.is_relative_to(source):
            raise ValueError("Documentation output and version inputs must not overlap")
    if output.exists() and not (output / MARKER).is_file():
        raise ValueError(f"Refusing to replace non-generated directory: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="mojoverse-versions-", dir=output.parent) as directory:
        site = Path(directory) / "site"
        site.mkdir()
        for name, source in sources.items():
            shutil.copytree(source, site / name)
        (site / "versions.json").write_text(json.dumps(VERSIONS, indent=2) + "\n")
        (site / ".nojekyll").touch()
        for page in sources["nightly"].rglob("*.html"):
            relative = page.relative_to(sources["nightly"])
            target = quote(os.path.relpath(Path("nightly") / relative, relative.parent))
            redirect = site / relative
            redirect.parent.mkdir(parents=True, exist_ok=True)
            redirect.write_text(
                '<!doctype html><html lang="en"><head><meta charset="utf-8">'
                '<title>Mojoverse documentation</title>'
                f'<script>location.replace({json.dumps(target)} + location.search + location.hash);</script>'
                f'<meta http-equiv="refresh" content="0; url={escape(target, quote=True)}">'
                f'</head><body><a href="{escape(target, quote=True)}">Open nightly documentation</a>'
                '</body></html>\n'
            )
        # Preserve existing API JSON download URLs as well as HTML page URLs.
        for api in sources["nightly"].rglob("*.json"):
            relative = api.relative_to(sources["nightly"])
            if relative == Path("versions.json"):
                continue
            destination = site / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(api, destination)
        (site / MARKER).write_text("Generated by scripts/assemble_docs.py.\n")
        if output.exists():
            shutil.rmtree(output)
        shutil.move(str(site), output)
